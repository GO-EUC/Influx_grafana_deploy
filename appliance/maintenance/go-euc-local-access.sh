#!/usr/bin/env bash

# Writes the nginx allow-list for /config.txt: the IPv4 subnet(s) the appliance itself is on.
# /config.txt is served without a login, but only to clients on those local subnets
# (everything else gets 403). Run again after the appliance's IP address changes;
# first boot and "Run Full Appliance Update" call it automatically.
#
# Docker networks (docker0, br-*, veth*) are never allowed: traffic relayed by Docker's
# userland proxy (e.g. IPv6 clients) appears to come from them, whatever its real origin.

set -euo pipefail

ALLOW_FILE="/opt/influx-grafana/nginx/auth/local-subnets.conf"

mapfile -t subnets < <(
  ip -o -4 addr show scope global 2>/dev/null \
    | awk '$2 != "docker0" && $2 !~ /^(br-|veth)/ {print $4}' \
    | python3 -c 'import ipaddress, sys
seen = []
for line in sys.stdin:
    line = line.strip()
    if not line:
        continue
    network = str(ipaddress.ip_interface(line).network)
    if network not in seen:
        seen.append(network)
print("\n".join(seen))'
)

mkdir -p "$(dirname "${ALLOW_FILE}")"
{
  echo "# Generated by go-euc-local-access.sh: clients allowed to read /config.txt without a login."
  for subnet in "${subnets[@]}"; do
    [[ -n "${subnet}" ]] && echo "allow ${subnet};"
  done
} > "${ALLOW_FILE}.tmp"
chmod 644 "${ALLOW_FILE}.tmp"
mv -f "${ALLOW_FILE}.tmp" "${ALLOW_FILE}"

if docker ps --format '{{.Names}}' 2>/dev/null | grep -q '^goeuc-nginx$'; then
  docker exec goeuc-nginx nginx -s reload >/dev/null 2>&1 || true
fi

if [[ "${#subnets[@]}" -eq 0 || -z "${subnets[0]:-}" ]]; then
  echo "[local-access] WARN: no local IPv4 subnet found; /config.txt is blocked for all clients."
else
  echo "[local-access] /config.txt readable without login from: ${subnets[*]}"
fi
